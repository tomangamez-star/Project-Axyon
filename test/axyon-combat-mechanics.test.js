'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const mechanics = require('../src/axyon-combat-mechanics')

const novice = { atk: 10, def: 5, spd: 5, str: 5, per: 5, sta: 5, vit: 5, fatigue: 0 }

test('legacy players receive safe baseline values for the new stats', () => {
  assert.deepEqual(mechanics.BASE_STATS, { str: 5, per: 5, sta: 5, vit: 5, fatigue: 0 })
})

test('fatigue reduces physical damage and STA lessens that penalty', () => {
  const tired = mechanics.fatiguePenalty(novice, 70)
  const resilient = mechanics.fatiguePenalty({ ...novice, sta: 15 }, 70)
  assert.ok(tired > resilient)
  assert.ok(mechanics.applyFatiguePenalty(100, novice, 70) < 100)
})

test('STR does not duplicate ATK and only adds a small physical bonus', () => {
  assert.equal(Math.max(0, novice.str - 5) * 0.35, 0)
  assert.equal(Math.max(0, 10 - 5) * 0.35, 1.75)
})

test('STA reduces fatigue generated by repeated physical actions', () => {
  const normal = mechanics.addFatigue(0, 'heavy', novice)
  const trained = mechanics.addFatigue(0, 'heavy', { ...novice, sta: 20 })
  assert.equal(normal, 12)
  assert.ok(trained < normal)
})

test('PER and SPD improve dodge odds while perfect dodges remain rarer', () => {
  const base = mechanics.dodgeChances(novice, 0)
  const trained = mechanics.dodgeChances({ ...novice, per: 18, spd: 18 }, 0)
  assert.ok(trained.perfect > base.perfect)
  assert.ok(trained.total > base.total)
  assert.ok(base.perfect < base.partial)
})

test('dodge resolves to perfect, partial or failed outcomes', () => {
  assert.equal(mechanics.resolveDodge(novice, 0, 0).result, 'perfect')
  assert.equal(mechanics.resolveDodge(novice, 0, 0.1).result, 'partial')
  assert.equal(mechanics.resolveDodge(novice, 0, 0.99).result, 'failed')
})

test('VIT increases restorative effects and provides an HP gain on training', () => {
  assert.equal(mechanics.enhancedHealing(novice, 10), 10)
  assert.equal(mechanics.enhancedHealing({ ...novice, vit: 11 }, 10), 12)
  assert.equal(mechanics.vitalityHpGain(novice), 5)
})

test('healing bonuses do not appear when an effect restores zero HP', () => {
  assert.equal(mechanics.enhancedHealing({ ...novice, vit: 50 }, 0), 0)
})

test('the live player damage formula uses STR and fatigue without replacing ATK', () => {
  const rpg = require('../src/axyon-rpg')
  const originalRandom = Math.random
  Math.random = () => 0
  try {
    const enemy = { def: 5 }
    const base = rpg.playerHit({ atk: 10, str: 5, sta: 5, fatigue: 0 }, enemy)
    const stronger = rpg.playerHit({ atk: 10, str: 10, sta: 5, fatigue: 0 }, enemy)
    const tired = rpg.playerHit({ atk: 10, str: 5, sta: 5, fatigue: 80 }, enemy)
    assert.ok(stronger > base)
    assert.ok(tired < base)
  } finally {
    Math.random = originalRandom
  }
})

test('VIT improves Soul Drain and other lifesteal recovery', () => {
  const items = require('../src/axyon-items')
  const drain = items.get('ability_drain')
  const result = items.apply(drain, {
    enemyHp: 100,
    playerHp: 50,
    mp: 50,
    guard: 0,
    enemy: { name: 'Test Enemy', hp: 100, atk: 1, def: 0 }
  }, { maxHp: 100, vit: 11, mp: 50, maxMp: 100 })
  assert.equal(result.battle.enemyHp, 60)
  assert.equal(result.battle.playerHp, 92)
})
